namespace Tessera.Controls;

/// <summary>
/// Defines the semantic tone applied to a <see cref="Badge"/>.
/// </summary>
public enum BadgeTone
{
    /// <summary>
    /// The default value.
    /// </summary>
    Default = 0,
    /// <summary>
    /// The success state.
    /// </summary>
    Success = 1,
    /// <summary>
    /// The warning state.
    /// </summary>
    Warning = 2,
    /// <summary>
    /// The error state.
    /// </summary>
    Error = 3,
}
