namespace Tessera.Controls;

/// <summary>
///     Identifies how a dialog was closed.
/// </summary>
public enum DialogResult
{
    /// <summary>
    ///     No value is selected.
    /// </summary>
    None = 0,

    /// <summary>
    ///     The accepted value.
    /// </summary>
    Accepted = 1,

    /// <summary>
    ///     The dismissed value.
    /// </summary>
    Dismissed = 2
}
