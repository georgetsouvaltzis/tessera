namespace Tessera.Controls;

/// <summary>
/// Identifies the active field within a time editor.
/// </summary>
public enum TimeField
{
    /// <summary>
    /// The hour value.
    /// </summary>
    Hour = 0,
    /// <summary>
    /// The minute value.
    /// </summary>
    Minute = 1,
    /// <summary>
    /// The second value.
    /// </summary>
    Second = 2,
}
