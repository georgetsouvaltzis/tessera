namespace Tessera.Controls;

/// <summary>
///     Defines the semantic severity of a notification entry.
/// </summary>
public enum NotificationLevel
{
    /// <summary>
    ///     The informational state.
    /// </summary>
    Info = 0,

    /// <summary>
    ///     The success state.
    /// </summary>
    Success = 1,

    /// <summary>
    ///     The warning state.
    /// </summary>
    Warning = 2,

    /// <summary>
    ///     The error state.
    /// </summary>
    Error = 3
}
