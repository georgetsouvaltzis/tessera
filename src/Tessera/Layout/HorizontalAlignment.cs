namespace Tessera.Layout;

/// <summary>
/// Specifies horizontal placement within the available layout space.
/// </summary>
public enum HorizontalAlignment
{
    /// <summary>
    /// The left value.
    /// </summary>
    Left = 0,
    /// <summary>
    /// The center value.
    /// </summary>
    Center = 1,
    /// <summary>
    /// The right value.
    /// </summary>
    Right = 2,
    /// <summary>
    /// The stretch value.
    /// </summary>
    Stretch = 3,
}
