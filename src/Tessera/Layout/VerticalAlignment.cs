namespace Tessera.Layout;

/// <summary>
///     Specifies vertical placement within the available layout space.
/// </summary>
public enum VerticalAlignment
{
    /// <summary>
    ///     The top value.
    /// </summary>
    Top = 0,

    /// <summary>
    ///     The center value.
    /// </summary>
    Center = 1,

    /// <summary>
    ///     The bottom value.
    /// </summary>
    Bottom = 2,

    /// <summary>
    ///     The stretch value.
    /// </summary>
    Stretch = 3
}
