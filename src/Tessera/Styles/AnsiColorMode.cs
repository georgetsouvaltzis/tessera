namespace Tessera.Styles;

/// <summary>
/// Represents ansi color mode.
/// </summary>
public enum AnsiColorMode
{
    /// <summary>
    /// The default value.
    /// </summary>
    Default = 0,
    /// <summary>
    /// The indexed value.
    /// </summary>
    Indexed = 1,
    /// <summary>
    /// The rgb value.
    /// </summary>
    Rgb = 2,
}
