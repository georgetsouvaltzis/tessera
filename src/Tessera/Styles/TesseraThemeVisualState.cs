namespace Tessera.Styles;

/// <summary>
/// Represents common visual states used by theme override resolution.
/// </summary>
public enum TesseraThemeVisualState
{
    /// <summary>
    /// The default value.
    /// </summary>
    Default = 0,
    /// <summary>
    /// The focused value.
    /// </summary>
    Focused = 1,
    /// <summary>
    /// The hovered value.
    /// </summary>
    Hovered = 2,
    /// <summary>
    /// The selected value.
    /// </summary>
    Selected = 3,
    /// <summary>
    /// The disabled value.
    /// </summary>
    Disabled = 4,
    /// <summary>
    /// The error state.
    /// </summary>
    Error = 5,
    /// <summary>
    /// The active value.
    /// </summary>
    Active = 6,
}
